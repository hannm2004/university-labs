    private void btnPathActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPathActionPerformed
        // TODO add your handling code here:
        this.fcpath.setVisible(true);

    // Thiết lập cho phép chọn tệp tin hay thư mục
    fcpath.setFileSelectionMode(JFileChooser.FILES_ONLY);

    // Cho hộp thoại hiển thị lên
    if (this.fcpath.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
        // Nếu nút Open được chọn
        try {
            txtFileName.setText(fcpath.getSelectedFile().getCanonicalPath());
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }
    }//GEN-LAST:event_btnPathActionPerformed

