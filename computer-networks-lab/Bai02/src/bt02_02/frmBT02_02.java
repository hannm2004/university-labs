    private void btnOutputStreamActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOutputStreamActionPerformed
        // TODO add your handling code here:
        byte a[] = new byte[20];
        File file;
        int i;
        char s[] = txtNhapChuoi.getText().toCharArray();
        for (i = 0; i < s.length; i++)
        {
            a[i] = (byte)s[i];
        }
        try {
            file = new File(txtFileName.getText());
            FileOutputStream fo = new FileOutputStream(file);
            fo.write(a);
            fo.close();
            } catch (IOException e) {e.printStackTrace();}
    }//GEN-LAST:event_btnOutputStreamActionPerformed

    private void btnInputStreamActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInputStreamActionPerformed
        // TODO add your handling code here:
        byte a[];
        File file;
        try {
            file = new File(txtFileName.getText());
            FileInputStream fi = new FileInputStream(file);
            a = new byte[fi.available()];
            fi.read(a);
            fi.close();
            txtNoiDungFile.setText(new String(a));
            } catch (Exception e) {}
    }//GEN-LAST:event_btnInputStreamActionPerformed

    private void btnWriterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnWriterActionPerformed
        // TODO add your handling code here:
        try{
            FileWriter fw = new FileWriter(new File(txtFileName.getText()));
            fw.write(txtNhapChuoi.getText());
            fw.close();    
        }catch(Exception e) {e.printStackTrace();}
    }//GEN-LAST:event_btnWriterActionPerformed

    private void btnReaderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReaderActionPerformed
        // TODO add your handling code here:
        try{
            FileReader fr = new FileReader(new File(txtFileName.getText()));
            StringBuffer sb = new StringBuffer();
            char ca[] = new char[5];
            while(fr.ready())
            {
                int len = fr.read(ca);
                sb.append(ca,0,len);
            }
            fr.close();
            txtNoiDungFile.setText(sb+"");
        }catch (Exception e){
            e.printStackTrace();
        }   
    }//GEN-LAST:event_btnReaderActionPerformed

