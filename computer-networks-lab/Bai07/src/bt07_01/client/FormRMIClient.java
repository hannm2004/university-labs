    private void btnCongSoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCongSoActionPerformed
        // TODO add your handling code here:
        try {
            String diaChi = txtDiaChi.getText().trim();

            java.rmi.registry.Registry r
                    = java.rmi.registry.LocateRegistry.getRegistry(diaChi, 3456);

            bt07_01.remoteapp.InterfaceCalc ic
                    = (bt07_01.remoteapp.InterfaceCalc) r.lookup("rmiCalc");

            int so1 = Integer.parseInt(txtSo1.getText().trim());
            int so2 = Integer.parseInt(txtSo2.getText().trim());

            int ketQua = ic.sum(so1, so2);

            txtKetQua.setText(String.valueOf(ketQua));

        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Loi cong hai so nguyen: " + ex.getMessage()
            );
        }
    }//GEN-LAST:event_btnCongSoActionPerformed

    private void btnCongPhanSoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCongPhanSoActionPerformed
        // TODO add your handling code here:
        try {
            String diaChi = txtDiaChi.getText().trim();

            java.rmi.registry.Registry r
                    = java.rmi.registry.LocateRegistry.getRegistry(diaChi, 3456);

            bt07_01.remoteapp.InterfaceCalc ic
                    = (bt07_01.remoteapp.InterfaceCalc) r.lookup("rmiCalc");

            int tuA = Integer.parseInt(txtTuA.getText().trim());
            int mauA = Integer.parseInt(txtMauA.getText().trim());
            int tuB = Integer.parseInt(txtTuB.getText().trim());
            int mauB = Integer.parseInt(txtMauB.getText().trim());

            if (mauA == 0 || mauB == 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Mau so khong duoc bang 0!"
                );
                return;
            }

            bt07_01.remoteapp.PhanSo a = new bt07_01.remoteapp.PhanSo(tuA, mauA);
            bt07_01.remoteapp.PhanSo b = new bt07_01.remoteapp.PhanSo(tuB, mauB);

            bt07_01.remoteapp.PhanSo c = ic.sum(a, b);

            txtKetQua.setText(c.getTu() + "/" + c.getMau());

        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Loi cong phan so: " + ex.getMessage()
            );
        }
    }//GEN-LAST:event_btnCongPhanSoActionPerformed

