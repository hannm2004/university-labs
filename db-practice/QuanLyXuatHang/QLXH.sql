CREATE FUNCTION F5(@MAPHIEUXUAT INT)
RETURNS NVARCHAR(100)
AS
	BEGIN
	DECLARE @TENNHANVIEN NVARCHAR(100)
	SET @TENNHANVIEN = (SELECT HOTEN
	FROM PHIEUXUAT P INNER JOIN NHANVIEN N ON P.MANV = N.MANV
	WHERE P.MAPX = @MAPHIEUXUAT)
	RETURN @TENNHANVIEN
	END

