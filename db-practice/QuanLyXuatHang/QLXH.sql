CREATE FUNCTION F1(@TENSANPHAM NVARCHAR(100),@NAM INT)
RETURNS INT
AS
BEGIN
	DECLARE @SOLUONG INT
	IF NOT EXISTS (SELECT *
	FROM SANPHAM
	WHERE TENSP = @TENSANPHAM)
	BEGIN
	SET @SOLUONG = 0
	END
	ELSE
	BEGIN
	SET @SOLUONG =  ISNULL((SELECT SUM(SL)
	FROM CTPX C INNER JOIN SANPHAM S ON C.MASP = S.MASP
	INNER JOIN PHIEUXUAT P ON C.MAPX = P.MAPX
	WHERE TENSP LIKE @TENSANPHAM AND YEAR(NGAYLAP) = @NAM),0)
	END
	RETURN @SOLUONG
END

