CREATE VIEW V1 AS
SELECT S.MASP,TENSP,SUM(SL)AS [TONGSOLUONG]
FROM PHIEUXUAT P INNER JOIN CTPX C ON P.MAPX = C.MAPX 
				INNER JOIN SANPHAM S ON S.MASP = c.MASP
WHERE YEAR(NGAYLAP) = 2010
GROUP BY S.MASP,TENSP
SELECT *
FROM V1
ORDER BY TENSP

CREATE VIEW V2 AS
SELECT S.MASP,TENSP,TENLOAI,NGAYLAP
FROM SANPHAM S INNER JOIN LOAI L ON S.MASP = L.MALOAI
				INNER JOIN CTPX C ON C.MASP = S.MASP
				INNER JOIN PHIEUXUAT P ON P.MAPX = C.MAPX
WHERE YEAR(NGAYLAP) = 2010 AND MONTH(NGAYLAP) BETWEEN 1 AND 6 AND DAY(NGAYLAP) BETWEEN 1 AND 31
SELECT *
FROM V2

CREATE VIEW V3 AS
