ALTER PROCEDURE P_LIETKEPHIEUXUAT
@X INT
AS
BEGIN 
DECLARE @MAPHIEUXUAT INT, @TENSANPHAM NVARCHAR(100), @SOLUONG BIGINT, @NGAY DATE,@ROW INT
DECLARE C_LIETKEPHIEUXUAT CURSOR FOR
	SELECT DISTINCT NGAYLAP,P.MAPX,TENSP,SL
FROM PHIEUXUAT P INNER JOIN CTPX C ON P.MAPX=C.MAPX
				INNER JOIN SANPHAM S ON S.MASP = C.MASP
				WHERE MONTH(NGAYLAP) = @X
				GROUP BY P.MAPX,TENSP,SL,NGAYLAP
OPEN C_LIETKEPHIEUXUAT
FETCH NEXT FROM C_LIETKEPHIEUXUAT INTO @NGAY,@MAPHIEUXUAT, @TENSANPHAM,@SOLUONG
SET @ROW =1
WHILE @@FETCH_STATUS = 0
BEGIN
PRINT N'Ngày' + CONVERT(VARCHAR(20),@NGAY) + CHAR(13) + CHAR(10)+ N'Phiếu số' + CONVERT(VARCHAR(5),@MAPHIEUXUAT) + N':' + @TENSANPHAM + N'-Số lượng:'+ CONVERT(VARCHAR(20),@SOLUONG)
FETCH NEXT FROM C_LIETKEPHIEUXUAT INTO @NGAY,@MAPHIEUXUAT, @TENSANPHAM,@SOLUONG
SET @ROW = @ROW + 1
END
CLOSE C_LIETKEPHIEUXUAT
DEALLOCATE C_LIETKEPHIEUXUAT
END

