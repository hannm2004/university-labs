FROM V9

CREATE VIEW V10 AS
SELECT TOP 1 WITH TIES SUM(SL) AS SOLUONGXUAT,S.MASP,TENSP
FROM PHIEUXUAT P INNER JOIN CTPX C ON P.MAPX = C.MAPX
					INNER JOIN SANPHAM S ON C.MASP = S.MASP
WHERE YEAR(NGAYLAP) = 2010
GROUP BY TENSP,S.MASP,TENSP
ORDER BY SUM(SL) DESC
