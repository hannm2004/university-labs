CREATE VIEW V1 AS
SELECT  TOP 1 WITH TIES TENLOAI,COUNT(*) AS SOLUONGSANPHAM
FROM SANPHAM S INNER JOIN LOAISP L ON S.MALOAI = L.MALOAI
GROUP BY TENLOAI
ORDER BY SOLUONGSANPHAM DESC

CREATE VIEW V2 AS
SELECT TENKH, DC
FROM KHACHHANG
WHERE MAKH NOT IN(
SELECT K.MAKH
FROM KHACHHANG K INNER JOIN DONDH D ON K.MAKH = D.MAKH
WHERE MONTH(NGAYDAT) = 3 AND YEAR(NGAYDAT) = 2010)

CREATE VIEW V3 AS
SELECT TOP 1 WITH TIES K.TENKH, DC, COUNT(D.SODDH) AS TONGSOHOADONDADAT
FROM KHACHHANG K INNER JOIN DONDH D ON K.MAKH = D.MAKH
WHERE MONTH(NGAYDAT) = 3 AND YEAR(NGAYDAT) = 2010
GROUP BY K.TENKH, DC
ORDER BY TONGSOHOADONDADAT DESC

CREATE VIEW V4 AS
SELECT TENSP,MOTA
FROM SANPHAM
WHERE MASP NOT IN (
SELECT S.MASP
FROM DONDH D INNER JOIN CTDDH C ON D.SODDH = C.SODDH
	INNER JOIN SANPHAM S ON S.MASP = C.MASP
WHERE MONTH(NGAYDAT) = 3 AND YEAR(NGAYDAT) = 2010)

CREATE VIEW V5 AS
SELECT TENKH,DC,SUM(SOLUONG) AS TONGTU
FROM DONDH D INNER JOIN CTDDH C ON D.SODDH = C.SODDH
	INNER JOIN SANPHAM S ON S.MASP = C.MASP
	INNER JOIN KHACHHANG K ON K.MAKH = D.MAKH
WHERE TENSP LIKE N'TỦ DDA'
GROUP BY TENKH,DC
HAVING SUM(SOLUONG) > 10

CREATE VIEW V6 AS
SELECT TOP 1 WITH TIES TENSP,S.GIA,LO.MALOAI, COUNT(MANL) AS SOLOAINGUYENLIEU
FROM SANPHAM S INNER JOIN LAM L ON L.MASP = S.MASP
			INNER JOIN LOAISP LO ON LO.MALOAI = S.MALOAI
GROUP BY TENSP,S.GIA,LO.MALOAI
ORDER BY COUNT(MANL) DESC

CREATE VIEW V7 AS
SELECT TENSP, SUM(L.SOLUONG * N.GIA) AS GIATHANHSX
FROM SANPHAM  S
INNER JOIN LAM L ON L.MASP = S.MASP
INNER JOIN NGUYENLIEU N ON N.MANL = L.MANL
GROUP BY TENSP
HAVING SUM(L.SOLUONG * N.GIA) > 1000000

CREATE VIEW V8 AS
SELECT TENSP, SUM(L.SOLUONG * N.GIA) AS GIATHANHSX,S.GIA,((S.GIA - SUM(L.SOLUONG * N.GIA)) / SUM(L.SOLUONG * N.GIA)) *100 AS PHANTRAMLAI
FROM SANPHAM  S
INNER JOIN LAM L ON L.MASP = S.MASP
INNER JOIN NGUYENLIEU N ON N.MANL = L.MANL
GROUP BY TENSP,S.GIA
HAVING ((S.GIA - SUM(L.SOLUONG * N.GIA)) / SUM(L.SOLUONG * N.GIA)) * 100 > 20

CREATE VIEW V9 AS
SELECT C.SODDH,NGAYDAT,SUM(S.GIA*SOLUONG) AS TONGTIEN
FROM CTDDH C INNER JOIN SANPHAM S ON C.MASP = S.MASP
INNER JOIN DONDH D ON D.SODDH = C.SODDH
GROUP BY C.SODDH,NGAYDAT
HAVING SUM(S.GIA*SOLUONG) > 100000000

CREATE VIEW V10 AS
SELECT N.TENNL, N.GIA
FROM NGUYENLIEU N
INNER JOIN LAM L ON N.MANL = L.MANL
INNER JOIN SANPHAM S ON S.MASP = L.MASP
GROUP BY N.TENNL, N.GIA
HAVING COUNT(DISTINCT S.MASP) = (SELECT COUNT(*) FROM SANPHAM)

CREATE VIEW V11 AS
SELECT K.TENKH, K.DC
FROM KHACHHANG K
INNER JOIN DONDH D ON K.MAKH = D.MAKH
INNER JOIN CTDDH C ON D.SODDH = C.SODDH
INNER JOIN SANPHAM S ON C.MASP = S.MASP
