CREATE DATABASE QLSANPHAM
USE QLSANPHAM
USE MASTER

CREATE TABLE LOAISP(
MALOAI CHAR(5) PRIMARY KEY,
TENLOAI NVARCHAR(10)
)

CREATE TABLE SANPHAM(
MASP CHAR(5) PRIMARY KEY,
TENSP NVARCHAR(20),
MOTA NVARCHAR(50),
GIA BIGINT,
MALOAI CHAR(5) FOREIGN KEY (MALOAI) REFERENCES LOAISP(MALOAI)
)

CREATE TABLE KHACHHANG(
MAKH CHAR(5) PRIMARY KEY,
TENKH NVARCHAR(30),
DC NVARCHAR(100),
DT CHAR(11)
)

CREATE TABLE DONDH (
    SODDH CHAR(5) PRIMARY KEY,
    NGAYDAT DATE,
    MAKH CHAR(5) FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH)
)

CREATE TABLE CTDDH (
    SODDH CHAR(5),
    MASP CHAR(5),
    SOLUONG INT,
    PRIMARY KEY (SODDH, MASP),
    FOREIGN KEY (SODDH) REFERENCES DONDH(SODDH),
	FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)
)

CREATE TABLE NGUYENLIEU (
    MANL CHAR(5) PRIMARY KEY,
    TENNL NVARCHAR(100),
    DVT NVARCHAR(10),
    GIA INT
)

CREATE TABLE LAM (
    MANL CHAR(5),
    MASP CHAR(5),
    SOLUONG FLOAT,
    PRIMARY KEY (MANL, MASP),
    FOREIGN KEY (MANL) REFERENCES NGUYENLIEU(MANL),
	FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)
	)

