CREATE PROCEDURE P5
    @X BIGINT
AS
BEGIN
    SELECT S.TENSP, 
           SUM(L.SOLUONG * N.GIA) AS GIATHANHSX,
           S.GIA AS GIABAN, 
           (S.GIA - SUM(L.SOLUONG * N.GIA)) AS LAI
    FROM SANPHAM S
    INNER JOIN LAM L ON S.MASP = L.MASP
    INNER JOIN NGUYENLIEU N ON L.MANL = N.MANL
    GROUP BY S.TENSP, S.GIA
    HAVING (S.GIA - SUM(L.SOLUONG * N.GIA)) > @X
END

EXEC P5 100000

