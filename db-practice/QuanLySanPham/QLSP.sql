    @MASP CHAR(5)
AS
BEGIN
    SELECT K.TENKH, K.DC
    FROM KHACHHANG K
    INNER JOIN DONDH D ON K.MAKH = D.MAKH
    INNER JOIN CTDDH C ON D.SODDH = C.SODDH
    WHERE C.MASP = @MASP
END

