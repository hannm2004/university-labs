CREATE VIEW V13 AS
SELECT K.TENKH, K.DC, K.MAKH
FROM KHACHHANG K
WHERE NOT EXISTS (
    SELECT 1
    FROM DONDH D
    WHERE D.MAKH = K.MAKH
