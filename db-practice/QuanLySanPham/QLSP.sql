CREATE PROCEDURE P3
    @X BIGINT
AS
BEGIN
    SELECT K.TENKH, K.DC
    FROM KHACHHANG K
    INNER JOIN DONDH D ON K.MAKH = D.MAKH
    INNER JOIN CTDDH C ON D.SODDH = C.SODDH
    INNER JOIN SANPHAM S ON C.MASP = S.MASP
    GROUP BY K.TENKH, K.DC, D.SODDH
    HAVING SUM(S.GIA * C.SOLUONG) > @X
END
EXEC P3 @X = 10000000;

