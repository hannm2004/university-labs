CREATE TRIGGER T3
ON CTDDH
AFTER INSERT, UPDATE
AS
BEGIN
    DECLARE @MASP CHAR(5), @SOLUONG INT, @GIA_BAN BIGINT, @GIA_SX INT, @LAILOSS DECIMAL(5,2)
    IF (SELECT COUNT(*) FROM INSERTED) > 1
    BEGIN
        RAISERROR('Chỉ có thể chèn hoặc cập nhật một dòng tại một thời điểm', 16, 1)
        ROLLBACK
        RETURN
    END
    SELECT @MASP = MASP, @SOLUONG = SOLUONG FROM INSERTED
    SELECT @GIA_BAN = GIA FROM SANPHAM WHERE MASP = @MASP
    SELECT @GIA_SX = SUM(L.SOLUONG * N.GIA)
    FROM LAM L
    INNER JOIN NGUYENLIEU N ON L.MANL = N.MANL
    WHERE L.MASP = @MASP
    SET @LAILOSS = ((@GIA_BAN - @GIA_SX) / @GIA_SX) * 100
    IF @LAILOSS < 50
    BEGIN
        PRINT('Sản phẩm này bị lỗ hơn 50%%, không thể thêm hoặc cập nhật đơn hàng.')
        ROLLBACK
    END
END

