CREATE PROCEDURE C2
AS
BEGIN
    DECLARE @MASP CHAR(5)
    DECLARE @GIA BIGINT
    DECLARE @GiaSX BIGINT;
    DECLARE @NewPrice BIGINT
    DECLARE product_cursor CURSOR FOR
    SELECT MASP, GIA
    FROM SANPHAM
    OPEN product_cursor
    FETCH NEXT FROM product_cursor INTO @MASP, @GIA
    WHILE @@FETCH_STATUS = 0
    BEGIN
        SELECT @GiaSX = SUM(L.SOLUONG * N.GIA)
        FROM LAM L
        INNER JOIN NGUYENLIEU N ON L.MANL = N.MANL
        WHERE L.MASP = @MASP;
        IF ((@GIA - @GiaSX) / @GiaSX) > 0.30
        BEGIN
            SET @NewPrice = @GIA * 0.9
        END
        ELSE IF (@GIA < @GiaSX)
        BEGIN
            SET @NewPrice = @GiaSX
        END
        ELSE
        BEGIN
            SET @NewPrice = @GIA * 1.05
        END
        UPDATE SANPHAM
        SET GIA = @NewPrice
        WHERE MASP = @MASP
        FETCH NEXT FROM product_cursor INTO @MASP, @GIA
    END
    CLOSE product_cursor
    DEALLOCATE product_cursor
END

